import ee
from . import common

# ---------------------------------------------------------------------------
# Stage 2 – Per-pixel masking helpers
# ---------------------------------------------------------------------------

def apply_scale_factors(img):
    """Apply USGS Collection 2 scale factors to surface reflectance and thermal bands."""
    opt = img.select('SR_B.*').multiply(0.0000275).add(-0.2)
    thm = img.select('ST_B.*').multiply(0.00341802).add(149.0)
    return img.addBands(opt, None, True).addBands(thm, None, True)


def cloud_mask_landsat(img):
    """
    Per-pixel cloud masking for Landsat 8/9 Collection 2 using the QA_PIXEL
    band generated by the CFMask algorithm.

    The QA_PIXEL band stores classification flags in specific bit positions.
    Four critical bits are evaluated; a pixel is ONLY preserved if ALL four
    flags are clear (== 0):

        Bit 1 – Dilated Cloud
        Bit 2 – Cirrus
        Bit 3 – Cloud
        Bit 4 – Cloud Shadow

    Each bit is isolated independently using bitwiseAnd() so that a single
    triggered flag is sufficient to mark the pixel as defective.

    Note on QA_RADSAT (Radiometric Saturation):
        Checking QA_RADSAT is intentionally bypassed for this agricultural
        monitoring use-case. Masking saturated pixels over-removes valid,
        highly-reflective surfaces such as greenhouse rooftops and bright
        bare soil, which do not adversely affect NDVI or other optical
        vegetation indices.
    """
    qa = img.select('QA_PIXEL')

    # Isolate each bit independently and require all to be 0 (clear)
    dilated_cloud  = qa.bitwiseAnd(1 << 1).eq(0)  # Bit 1: Dilated Cloud
    cirrus         = qa.bitwiseAnd(1 << 2).eq(0)  # Bit 2: Cirrus
    cloud          = qa.bitwiseAnd(1 << 3).eq(0)  # Bit 3: Cloud
    cloud_shadow   = qa.bitwiseAnd(1 << 4).eq(0)  # Bit 4: Cloud Shadow

    # A pixel is valid only when ALL four flags are clear
    clear_mask = dilated_cloud.And(cirrus).And(cloud).And(cloud_shadow)

    return img.updateMask(clear_mask)


# ---------------------------------------------------------------------------
# Stage 1 – Scene-level relaxed gate + collection builder
# ---------------------------------------------------------------------------

def get_landsat_collection(aoi, start_date, end_date, cloud_filter=100):
    """
    Get merged Landsat 8/9 collection using the two-stage cloud filtering strategy.

    Stage 1 – Scene-level Relaxed Gate:
        Only discard scenes where CLOUD_COVER == 100 (completely unusable).
        Partially cloudy scenes are retained so that clean pixels within the
        AOI are not discarded along with cloudy portions elsewhere in the scene.

    Stage 2 – Per-pixel QA_PIXEL masking (CFMask):
        cloud_mask_landsat() removes individual cloud, cloud-shadow, cirrus,
        and dilated-cloud pixels, making them transparent (NaN). Downstream
        daily mosaicking then gap-fills: a masked pixel from overpass A is
        automatically replaced by a clear pixel from overlapping overpass B
        on the same acquisition date.

    Args:
        aoi          : ee.Geometry – Area of interest.
        start_date   : str – Start date 'YYYY-MM-DD'.
        end_date     : str – End date 'YYYY-MM-DD'.
        cloud_filter : Scene-level gate (default 100 → keep everything that
                       isn't 100 % cloud-covered). Adjust to 50 for stricter
                       scene rejection while still benefiting from per-pixel masking.
    """
    # Stage 1: Relaxed scene-level gate – merge Landsat 8 + 9
    merged = (
        ee.ImageCollection('LANDSAT/LC08/C02/T1_L2')
        .merge(ee.ImageCollection('LANDSAT/LC09/C02/T1_L2'))
        .filterBounds(aoi)
        .filterDate(start_date, end_date)
        .filter(ee.Filter.lt('CLOUD_COVER', cloud_filter))
    )

    # Add date string for grouping by acquisition date
    with_date = merged.map(
        lambda img: img.set('date_str', img.date().format('YYYY-MM-dd'))
    )

    # -----------------------------------------------------------------------
    # Daily mosaic – select best image per day (lowest scene cloud cover),
    # then gap-fill across same-day overpasses via per-pixel masking.
    # -----------------------------------------------------------------------
    unique_dates = with_date.aggregate_array('date_str').distinct()

    one_per_day = ee.ImageCollection(
        unique_dates.map(
            lambda d:
                with_date
                .filterDate(d, ee.Date(d).advance(1, 'day'))
                .sort('CLOUD_COVER')
                .first()
                .set('selected_date', d)
        )
    ).sort('system:time_start')

    return one_per_day


